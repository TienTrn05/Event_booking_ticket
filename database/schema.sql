SET client_encoding = 'UTF8';
SET TIME ZONE 'UTC';
BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    avatar_url VARCHAR(1000) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    auth_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT ck_users_name CHECK (CHAR_LENGTH(TRIM(display_name)) > 0),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE','BLOCKED'))
);
CREATE INDEX ix_users_status_created ON users (status, created_at, id);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code VARCHAR(48) NOT NULL,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_roles_code UNIQUE (code)
);

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code VARCHAR(80) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_permissions_code UNIQUE (code)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    granted_by BIGINT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles(id),
    CONSTRAINT fk_user_roles_granter FOREIGN KEY (granted_by) REFERENCES users(id)
);
CREATE INDEX ix_user_roles_role ON user_roles (role_id, user_id);
CREATE INDEX ix_user_roles_granter ON user_roles (granted_by);

CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id) REFERENCES roles(id),
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id) REFERENCES permissions(id)
);
CREATE INDEX ix_role_permissions_permission ON role_permissions (permission_id, role_id);

CREATE TABLE external_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id BIGINT NOT NULL,
    provider VARCHAR(24) NOT NULL,
    subject VARCHAR(254) NOT NULL,
    email_canonical VARCHAR(254) NULL,
    email_verified_at TIMESTAMPTZ(6) NULL,
    hosted_domain VARCHAR(253) NULL,
    verified_at TIMESTAMPTZ(6) NOT NULL,
    revoked_at TIMESTAMPTZ(6) NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_identity_provider_subject UNIQUE (provider, subject),
    CONSTRAINT uq_identity_owner UNIQUE (id, user_id),
    CONSTRAINT uq_identity_company_owner UNIQUE (id, user_id, provider),
    CONSTRAINT fk_identity_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_identity_provider CHECK (provider IN ('GOOGLE','PHONE','EMAIL','COMPANY_EMAIL')),
    CONSTRAINT ck_identity_subject CHECK (CHAR_LENGTH(subject) > 0),
    CONSTRAINT ck_identity_email CHECK (
        (provider = 'PHONE' AND email_canonical IS NULL AND email_verified_at IS NULL AND hosted_domain IS NULL)
        OR (provider IN ('EMAIL','COMPANY_EMAIL') AND email_canonical IS NOT NULL AND email_verified_at IS NOT NULL
            AND hosted_domain IS NULL AND subject = email_canonical)
        OR (provider = 'GOOGLE' AND (email_verified_at IS NULL OR email_canonical IS NOT NULL))
    )
);
CREATE INDEX ix_identity_user ON external_identities (user_id, id);
CREATE INDEX ix_identity_google_email ON external_identities(email_canonical) WHERE provider='GOOGLE';

-- Phone is an unverified login alias. EMAIL owns the authentication proof.
CREATE TABLE phone_login_aliases (
    phone VARCHAR(16) PRIMARY KEY,
    email_identity_id BIGINT NOT NULL REFERENCES external_identities(id),
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT ck_login_alias_phone CHECK (phone ~ '^\+[1-9][0-9]{7,14}$')
);
CREATE INDEX ix_login_alias_identity ON phone_login_aliases(email_identity_id);

CREATE TABLE otp_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    challenge_id BYTEA NOT NULL,
    channel VARCHAR(24) NOT NULL,
    purpose VARCHAR(24) NOT NULL,
    target_canonical VARCHAR(254) NOT NULL,
    target_hash BYTEA NOT NULL,
    code_mac BYTEA NOT NULL,
    mac_key_version VARCHAR(48) NOT NULL,
    user_id BIGINT NULL,
    browser_binding_hash BYTEA NOT NULL,
    login_phone VARCHAR(16) NULL,
    delivery_ready BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMPTZ(6) NOT NULL,
    attempts SMALLINT NOT NULL DEFAULT 0,
    max_attempts SMALLINT NOT NULL DEFAULT 5,
    used_at TIMESTAMPTZ(6) NULL,
    revoked_at TIMESTAMPTZ(6) NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_otp_public_challenge UNIQUE (challenge_id),
    CONSTRAINT fk_otp_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_otp_channel CHECK (channel IN ('PHONE','EMAIL','COMPANY_EMAIL')),
    CONSTRAINT ck_otp_purpose CHECK (purpose IN ('LOGIN','LINK_IDENTITY','REAUTHENTICATE')),
    CONSTRAINT ck_otp_bound_user CHECK (purpose = 'LOGIN' OR user_id IS NOT NULL),
    CONSTRAINT ck_otp_attempts CHECK (max_attempts > 0 AND attempts <= max_attempts),
    CONSTRAINT ck_otp_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_otp_used CHECK (used_at IS NULL OR (used_at >= created_at AND used_at < expires_at)),
    CONSTRAINT ck_otp_target CHECK (CHAR_LENGTH(TRIM(target_canonical)) > 0),
    CONSTRAINT ck_otp_login_phone CHECK (login_phone IS NULL OR (channel='EMAIL' AND login_phone ~ '^\+[1-9][0-9]{7,14}$'))
);
CREATE INDEX ix_otp_target_purpose ON otp_challenges (target_hash, channel, purpose, created_at, id);
CREATE INDEX ix_otp_user ON otp_challenges (user_id);
CREATE INDEX ix_otp_expiry ON otp_challenges (expires_at, id);

CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(180) NOT NULL,
    company_domain VARCHAR(253) NOT NULL,
    applicant_user_id BIGINT NOT NULL,
    company_identity_id BIGINT NOT NULL,
    company_identity_provider VARCHAR(24) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_REVIEW',
    version INTEGER NOT NULL DEFAULT 0,
    reviewed_by BIGINT NULL,
    reviewed_at TIMESTAMPTZ(6) NULL,
    review_reason VARCHAR(2000) NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_org_applicant FOREIGN KEY (applicant_user_id) REFERENCES users(id),
    CONSTRAINT fk_org_company_identity FOREIGN KEY (company_identity_id, applicant_user_id, company_identity_provider)
        REFERENCES external_identities(id, user_id, provider),
    CONSTRAINT fk_org_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),
    CONSTRAINT ck_org_company_provider CHECK (company_identity_provider IN ('GOOGLE','COMPANY_EMAIL')),
    CONSTRAINT ck_org_status CHECK (status IN ('PENDING_REVIEW','APPROVED','REJECTED','SUSPENDED')),
    CONSTRAINT ck_org_review CHECK (
        (status = 'PENDING_REVIEW' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR (status IN ('APPROVED','REJECTED','SUSPENDED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT ck_org_reason CHECK (status NOT IN ('REJECTED','SUSPENDED') OR
        (review_reason IS NOT NULL AND CHAR_LENGTH(TRIM(review_reason)) > 0)),
    CONSTRAINT ck_org_fields CHECK (CHAR_LENGTH(TRIM(name)) > 0 AND CHAR_LENGTH(company_domain) > 0)
);
CREATE INDEX ix_org_applicant ON organizations (applicant_user_id, id);
CREATE INDEX ix_org_identity_scope ON organizations (company_identity_id, applicant_user_id, company_identity_provider);
CREATE INDEX ix_org_reviewer ON organizations (reviewed_by);
CREATE INDEX ix_org_review_queue ON organizations (status, created_at, id);


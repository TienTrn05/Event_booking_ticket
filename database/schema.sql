CREATE FUNCTION guard_reputation_entry() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE original organization_reputation_entries%ROWTYPE;
BEGIN
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'Reputation ledger is append only' USING ERRCODE='23514'; END IF;
 IF NEW.reverses_entry_id IS NOT NULL THEN
  SELECT * INTO original FROM organization_reputation_entries WHERE id=NEW.reverses_entry_id;
  IF original.id IS NULL OR original.organization_id<>NEW.organization_id OR original.reverses_entry_id IS NOT NULL OR original.delta<>-NEW.delta THEN
   RAISE EXCEPTION 'Invalid reputation reversal' USING ERRCODE='23514';
  END IF;
 ELSIF NOT EXISTS(SELECT 1 FROM support_reports r JOIN events e ON e.id=r.event_id WHERE r.id=NEW.source_report_id AND r.status='RESOLVED' AND e.organization_id=NEW.organization_id) THEN
  RAISE EXCEPTION 'Invalid reputation source' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END; $$;

-- Chạy trên database đã có schema 38 bảng trước đây. Chọn đúng database trong DBeaver trước khi chạy script.
-- Migration chỉ thêm bảng catalog/public content; không DROP hoặc tắt FK checks.
SET client_encoding = 'UTF8';
SET TIME ZONE 'UTC';
BEGIN;

CREATE TABLE organization_profiles (
    organization_id BIGINT NOT NULL,
    public_id VARCHAR(80) NOT NULL,
    avatar_url VARCHAR(1000) NOT NULL,
    summary VARCHAR(1000) NOT NULL,
    category_label VARCHAR(120) NOT NULL,
    featured_rank SMALLINT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (organization_id),
    CONSTRAINT uq_org_profile_public_id UNIQUE (public_id),
    CONSTRAINT uq_org_profile_featured_rank UNIQUE (featured_rank),
    CONSTRAINT fk_org_profile_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT ck_org_profile_text CHECK (CHAR_LENGTH(TRIM(summary)) > 0 AND CHAR_LENGTH(TRIM(category_label)) > 0)
);

CREATE TABLE event_publications (
    event_id BIGINT NOT NULL,
    public_id VARCHAR(80) NOT NULL,
    display_name VARCHAR(180) NOT NULL,
    cover_image_url VARCHAR(1000) NOT NULL,
    card_badge VARCHAR(80) NULL,
    admission_type VARCHAR(16) NOT NULL,
    catalog_status VARCHAR(24) NOT NULL,
    starting_price_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    featured_rank SMALLINT NULL,
    spotlight_rank SMALLINT NULL,
    reopening_note VARCHAR(1000) NULL,
    published_at TIMESTAMPTZ(6) NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (event_id),
    CONSTRAINT uq_event_publication_public_id UNIQUE (public_id),
    CONSTRAINT uq_event_publication_featured_rank UNIQUE (featured_rank),
    CONSTRAINT uq_event_publication_spotlight_rank UNIQUE (spotlight_rank),
    CONSTRAINT fk_event_publication_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT ck_event_publication_admission CHECK (admission_type IN ('NUMBERED','QUANTITY')),
    CONSTRAINT ck_event_publication_status CHECK (catalog_status IN ('ON_SALE','FEW_LEFT','SOLD_OUT','COMING_SOON')),
    CONSTRAINT ck_event_publication_price CHECK (starting_price_minor >= 0),
    CONSTRAINT ck_event_publication_currency CHECK (currency = UPPER(currency) AND currency ~ '^[A-Z]{3}$')
);

CREATE TABLE city_profiles (
    city VARCHAR(120) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    image_url VARCHAR(1000) NOT NULL,
    sort_order SMALLINT NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (city),
    CONSTRAINT uq_city_profile_sort UNIQUE (sort_order),
    CONSTRAINT ck_city_profile_text CHECK (CHAR_LENGTH(TRIM(city)) > 0 AND CHAR_LENGTH(TRIM(display_name)) > 0)
);

CREATE TABLE merchandise_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_id VARCHAR(80) NOT NULL,
    event_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    name VARCHAR(180) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    image_url VARCHAR(1000) NOT NULL,
    price_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    badge VARCHAR(48) NULL,
    requires_ticket BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_merchandise_public_id UNIQUE (public_id),
    CONSTRAINT uq_merchandise_event_org UNIQUE (id, event_id, organization_id),
    CONSTRAINT fk_merchandise_event_org FOREIGN KEY (event_id, organization_id) REFERENCES events(id, organization_id),
    CONSTRAINT fk_merchandise_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT ck_merchandise_price CHECK (price_minor >= 0),
    CONSTRAINT ck_merchandise_currency CHECK (currency = UPPER(currency) AND currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_merchandise_ticket CHECK (requires_ticket IN (FALSE, TRUE)),
    CONSTRAINT ck_merchandise_status CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED'))
);
CREATE INDEX ix_merchandise_event_status ON merchandise_products (event_id, status, sort_order);
CREATE INDEX ix_merchandise_org_status ON merchandise_products (organization_id, status, sort_order);

CREATE TABLE blog_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    slug VARCHAR(160) NOT NULL,
    title VARCHAR(255) NOT NULL,
    excerpt VARCHAR(1000) NOT NULL,
    body_json JSONB NOT NULL,
    image_url VARCHAR(1000) NOT NULL,
    category VARCHAR(80) NOT NULL,
    read_minutes SMALLINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMPTZ(6) NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_blog_article_slug UNIQUE (slug),
    CONSTRAINT ck_blog_article_body CHECK (jsonb_typeof(body_json) = 'array'),
    CONSTRAINT ck_blog_article_read_time CHECK (read_minutes > 0),
    CONSTRAINT ck_blog_article_status CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED'))
);
CREATE INDEX ix_blog_article_publication ON blog_articles (status, published_at, id);

CREATE TABLE event_change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_id VARCHAR(80) NOT NULL,
    event_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    requested_by BIGINT NOT NULL,
    request_type VARCHAR(32) NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    impact_summary VARCHAR(2000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    visible_on_catalog BOOLEAN NOT NULL DEFAULT FALSE,
    requested_at TIMESTAMPTZ(6) NOT NULL,
    decided_by BIGINT NULL,
    decided_at TIMESTAMPTZ(6) NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_event_change_public_id UNIQUE (public_id),
    CONSTRAINT fk_event_change_event_org FOREIGN KEY (event_id, organization_id) REFERENCES events(id, organization_id),
    CONSTRAINT fk_event_change_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_event_change_requester FOREIGN KEY (requested_by) REFERENCES users(id),
    CONSTRAINT fk_event_change_decider FOREIGN KEY (decided_by) REFERENCES users(id),
    CONSTRAINT ck_event_change_type CHECK (request_type IN ('CAPACITY','NEW_SALE_WAVE','SALES_CONFIG','RESUME_SALES')),
    CONSTRAINT ck_event_change_status CHECK (status IN ('PENDING','APPROVED','REJECTED','WITHDRAWN')),
    CONSTRAINT ck_event_change_visible CHECK (visible_on_catalog IN (FALSE, TRUE) AND (visible_on_catalog = FALSE OR status = 'APPROVED')),
    CONSTRAINT ck_event_change_decision CHECK (
      (status = 'PENDING' AND decided_by IS NULL AND decided_at IS NULL)
      OR (status IN ('APPROVED','REJECTED') AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
      OR (status = 'WITHDRAWN' AND decided_at IS NOT NULL)
    )
);
CREATE INDEX ix_event_change_event_status ON event_change_requests (event_id, status, requested_at);
CREATE INDEX ix_event_change_org_status ON event_change_requests (organization_id, status, requested_at);


CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_organization_profiles_updated_at BEFORE UPDATE ON organization_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_event_publications_updated_at BEFORE UPDATE ON event_publications
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_city_profiles_updated_at BEFORE UPDATE ON city_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_merchandise_products_updated_at BEFORE UPDATE ON merchandise_products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_blog_articles_updated_at BEFORE UPDATE ON blog_articles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_event_change_requests_updated_at BEFORE UPDATE ON event_change_requests
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;

-- Published question sets have an independent lifecycle; no existing config table serves it.
-- Keep archived versions and User answers. Back up before applying, after 008/009.
BEGIN;
CREATE TABLE onboarding_questionnaires (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 questions JSONB NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 created_by BIGINT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT ck_questionnaire_status CHECK(status IN ('ACTIVE','ARCHIVED')),
 CONSTRAINT ck_questionnaire_questions CHECK(jsonb_typeof(questions)='array' AND jsonb_array_length(questions)<=20)
);
CREATE UNIQUE INDEX uq_questionnaire_active ON onboarding_questionnaires(status) WHERE status='ACTIVE';
INSERT INTO onboarding_questionnaires(questions) VALUES('[
 {"key":"favoriteCategories","kind":"CATEGORIES","label":"Danh mục yêu thích","required":false},
 {"key":"preferredCity","kind":"CITY","label":"Thành phố","required":false},
 {"key":"followedOrganizers","kind":"ORGANIZERS","label":"Nhà tổ chức quan tâm","required":false}
]');
ALTER TABLE users ADD COLUMN onboarding_questionnaire_id BIGINT NULL REFERENCES onboarding_questionnaires(id),
 ADD COLUMN onboarding_answers JSONB NOT NULL DEFAULT '{}',
 ADD CONSTRAINT ck_onboarding_answers CHECK(jsonb_typeof(onboarding_answers)='object');
INSERT INTO permissions(code,description) VALUES('onboarding.manage','Admin quản lý câu hỏi bổ sung, giữ bốn trường lõi bắt buộc') ON CONFLICT DO NOTHING;
INSERT INTO role_permissions(role_id,permission_id) SELECT r.id,p.id FROM roles r CROSS JOIN permissions p WHERE r.code='ADMIN' AND p.code='onboarding.manage' ON CONFLICT DO NOTHING;
COMMIT;

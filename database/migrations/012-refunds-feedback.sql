-- Reuse refunds/reports; a shared feedback lifecycle serves organization and app comments.
BEGIN;
ALTER TABLE refunds ADD COLUMN version INTEGER NOT NULL DEFAULT 0,
 ADD COLUMN decision_reason VARCHAR(1000), ADD COLUMN approved_at TIMESTAMPTZ(6),
 ADD COLUMN recorded_by BIGINT REFERENCES users(id), ADD COLUMN recorded_at TIMESTAMPTZ(6),
 ADD COLUMN evidence_note VARCHAR(2000), ADD COLUMN transferred_at TIMESTAMPTZ(6),
 ADD CONSTRAINT ck_refund_manual_success CHECK(status<>'SUCCESS' OR
  (recorded_by IS NOT NULL AND recorded_at IS NOT NULL AND provider_reference IS NOT NULL
   AND evidence_note IS NOT NULL AND char_length(trim(evidence_note))>=10 AND transferred_at IS NOT NULL)),
 ADD CONSTRAINT ck_refund_manual_processing CHECK(status NOT IN ('PROCESSING','FAILED','SUCCESS') OR
  (approved_by IS NOT NULL AND approved_at IS NOT NULL));
CREATE TABLE feedback (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id BIGINT NOT NULL REFERENCES users(id),
 kind VARCHAR(16) NOT NULL, organization_id BIGINT REFERENCES organizations(id),
 event_id BIGINT, category VARCHAR(24) NOT NULL,
 stars SMALLINT, content VARCHAR(2000) NOT NULL,
 status VARCHAR(16) NOT NULL, version INTEGER NOT NULL DEFAULT 0,
 reply VARCHAR(2000), replied_by BIGINT REFERENCES users(id), replied_at TIMESTAMPTZ(6),
 moderation_reason VARCHAR(1000),
 history JSONB NOT NULL DEFAULT '[]',
 created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_feedback_event_org FOREIGN KEY(event_id,organization_id) REFERENCES events(id,organization_id),
 CONSTRAINT uq_feedback_author_event UNIQUE(author_id,event_id),
 CONSTRAINT ck_feedback_target CHECK (
  (kind='ORGANIZATION' AND organization_id IS NOT NULL AND event_id IS NOT NULL AND stars IS NOT NULL AND category='EVENT' AND status IN ('VISIBLE','HIDDEN')) OR
  (kind='SYSTEM' AND organization_id IS NULL AND event_id IS NULL AND category IN ('BUG','PERFORMANCE','USABILITY','OTHER') AND status IN ('OPEN','IN_REVIEW','RESOLVED'))),
 CONSTRAINT ck_feedback_stars CHECK(stars BETWEEN 1 AND 5),
 CONSTRAINT ck_feedback_content CHECK(char_length(trim(content)) BETWEEN 3 AND 2000),
 CONSTRAINT ck_feedback_history CHECK(jsonb_typeof(history)='array'),
 CONSTRAINT ck_feedback_hidden CHECK(status<>'HIDDEN' OR (moderation_reason IS NOT NULL AND char_length(trim(moderation_reason))>0)),
 CONSTRAINT ck_feedback_reply CHECK ((reply IS NULL AND replied_by IS NULL AND replied_at IS NULL) OR (reply IS NOT NULL AND replied_by IS NOT NULL AND replied_at IS NOT NULL))
);
CREATE INDEX ix_feedback_author ON feedback(author_id,id);
CREATE INDEX ix_feedback_org ON feedback(organization_id,id);
CREATE INDEX ix_feedback_admin ON feedback(kind,status,id);
CREATE TRIGGER trg_feedback_updated_at BEFORE UPDATE ON feedback FOR EACH ROW EXECUTE FUNCTION set_updated_at();
INSERT INTO permissions(code,description) VALUES
 ('feedback.manage','Admin đọc và xử lý feedback hệ thống/tổ chức'),
 ('feedback.reply_own','Organizer xem và trả lời đánh giá tổ chức mình') ON CONFLICT DO NOTHING;
INSERT INTO role_permissions(role_id,permission_id) SELECT r.id,p.id FROM roles r CROSS JOIN permissions p
 WHERE (r.code='ADMIN' AND p.code='feedback.manage') OR (r.code='ORGANIZER' AND p.code='feedback.reply_own') ON CONFLICT DO NOTHING;
COMMIT;
